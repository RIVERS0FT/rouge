import plan from '../data/southeast-asia-gameplay-regions.json' with {type:'json'};
const touched=new Set(plan.regions.flatMap(row=>Object.values(row.groups).flat()));
export const isSeaBatch=id=>touched.has(id);
import next from '../data/asia-arabia-gameplay-regions.json' with {type:'json'};
const latest=new Set(next.regions.flatMap(row=>Object.values(row.groups).flat()));
export const isAsiaArabia=id=>latest.has(id);
export const isSeaOrAsiaArabia=id=>isSeaBatch(id)||isAsiaArabia(id);
import europe from '../data/europe-gameplay-regions.json' with {type:'json'};
const european=new Set(europe.regions.flatMap(row=>Object.values(row.groups).flat()));
export const isEuropeBatch=id=>european.has(id);
export const isAnyLatestGrouping=id=>isSeaOrAsiaArabia(id)||isEuropeOrGlobalIslands(id);
import smallEurope from '../data/europe-small-gameplay-regions.json' with {type:'json'};
const smallEuropean=new Set(smallEurope.regions.flatMap(row=>Object.values(row.members).flat()));
export const isSmallEuropeBatch=id=>smallEuropean.has(id);
export const isAnyEuropeBatch=id=>isEuropeBatch(id)||isSmallEuropeBatch(id);
import islandPlan from '../data/global-island-gameplay-regions.json' with {type:'json'};
const islandTouched=new Set(islandPlan.regions.flatMap(row=>Object.values(row.groups).flat()));
export const isGlobalIslands=id=>islandTouched.has(id);
export const isEuropeOrGlobalIslands=id=>isAnyEuropeBatch(id)||isGlobalIslands(id);
