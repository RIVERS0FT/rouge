import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import asc from 'assemblyscript/asc';

const input='scripts/simulation-kernel.as.ts',output='src/generated/simulationKernel.ts';
const options=['--optimizeLevel','3','--shrinkLevel','0','--runtime','stub','--noAssert','--initialMemory','1','--debug'];
const source=await readFile(input,'utf8'),compiler=JSON.parse(await readFile(new URL('../node_modules/assemblyscript/package.json',import.meta.url),'utf8')).version;
const hash=createHash('sha256').update(JSON.stringify({source,compiler,options})).digest('hex'),stamp=`// source-sha256: ${hash}`;
let previous='';try{previous=await readFile(output,'utf8');}catch{}
if(previous.includes(stamp)){console.log('Simulation kernel is current');process.exit(0);}
await mkdir('.cache/simulation-build',{recursive:true});const wasm=resolve('.cache/simulation-build/kernel.wasm');
const result=await asc.main([input,'-o',wasm,...options],{stdout:process.stdout,stderr:process.stderr});if(result.error)throw result.error;
const bytes=await readFile(wasm),text=`// Generated by scripts/build-simulation.mjs; AssemblyScript ${compiler}.\n${stamp}\nexport const KERNEL_BYTES=Uint8Array.from(atob('${bytes.toString('base64')}'),c=>c.charCodeAt(0));\n`;
await writeFile(output,text);console.log(`Built simulation kernel (${bytes.byteLength} bytes)`);
