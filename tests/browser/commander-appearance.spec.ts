function meanColorChange(first:Buffer,second:Buffer){
 const a=imageTools.PNG.sync.read(first).data,b=imageTools.PNG.sync.read(second).data;
 expect(a.length).toBe(b.length);
 let total=0;
 for(let i=0;i<a.length;i+=4)total+=Math.abs(a[i]-b[i])+Math.abs(a[i+1]-b[i+1])+Math.abs(a[i+2]-b[i+2]);
 return total/(a.length/4*3);
}

